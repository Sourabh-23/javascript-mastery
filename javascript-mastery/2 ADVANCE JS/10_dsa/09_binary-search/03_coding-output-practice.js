// Q1. binary search found
{
  function search(nums, target) {
    let l = 0;
    let r = nums.length - 1;
    while (l <= r) {
      const m = Math.floor((l + r) / 2);
      if (nums[m] === target) return m;
      if (nums[m] < target) l = m + 1;
      else r = m - 1;
    }
    return -1;
  }

  // Input:
  search([1, 3, 5], 5);

  // Answer:
  // 2
}

