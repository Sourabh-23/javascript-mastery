// PDF Q651. Write a JavaScript function for linear search and handle empty input.
{
  function linearSearch(items) {
    const seen = new Set();
    const result = [];
    for (const item of items) {
      if (!seen.has(item)) {
        seen.add(item);
        result.push(item);
      }
    }
    return result;
  }

  // Input:
  linearSearch([1, 1, 2, 3]);

  // Answer:
  // [1, 2, 3]
}

