// PDF Q601. Write a JavaScript function for stack and handle empty input.
{
  function stack(items) {
    const stack = [...items];
    const reversed = [];
    while (stack.length) reversed.push(stack.pop());
    return reversed;
  }

  // Input:
  stack([1, 2, 3]);

  // Answer:
  // [3, 2, 1]
}

