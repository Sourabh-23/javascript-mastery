// PDF Q501. Write a JavaScript function for create element and handle empty input.
{
  function element(nodes, id) {
    const element = nodes.find((node) => node.id === id);
    if (!element) return '';
    element.clicked = true;
    return element.text;
  }

  // Input:
  element([{ id: 'btn', text: 'Save' }], 'btn');

  // Answer:
  // "Save"
}

